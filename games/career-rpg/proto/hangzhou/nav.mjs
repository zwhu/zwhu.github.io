// 房间放得下时按整数倍取整；比一张底图更窄时铺满宽度，字号另有 13px 下限。
export function stagePixels(avail, worldWidth = WORLD.w) {
  if (avail >= worldWidth) return Math.floor(avail / worldWidth) * worldWidth;
  return avail;
}

